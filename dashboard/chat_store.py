"""Persistent chat history in MongoDB.

Streamlit keeps conversation state in st.session_state, which lives only as
long as the browser tab. Refresh the page and the conversation is gone. This
stores conversations and their messages so they survive a refresh, a server
restart, and a machine reboot, and so several conversations can be kept side
by side and switched between.

WHAT IS DELIBERATELY NOT STORED: the Plotly figures. An astronomy answer
carries three, one of which plots a 65,000-point light curve, and
fig.to_json() on that runs to about a megabyte. A handful of conversations
would be hundreds of megabytes of chart JSON, for figures that can be
regenerated by re-asking. Loaded history therefore shows text, traces and
retrieved context, and the charts reappear on any fresh answer.

DEGRADES TO NOTHING. Every function here returns an empty result rather than
raising if Mongo is unreachable, and the caller treats history as a
convenience rather than a dependency -- a dead database should cost the
sidebar, not the chatbot. is_available() says which mode the UI is in.

Two collections:
  conversations -- {_id, title, created_at, updated_at, n_messages}
  messages      -- {_id, conversation_id, role, content, trace,
                    retrieved_context, domain, created_at, seq}
"""

import os
from datetime import datetime, timezone

MONGO_URI = os.environ.get("MONGODB_URI", "mongodb://localhost:27017")
MONGO_DB = os.environ.get("MONGODB_DB", "btp_chat")

_CONNECT_TIMEOUT_MS = 2500      # the UI should not hang on a dead database

_client = None
_unavailable_reason = None


def _db():
    """A cached client, or None. Never raises."""
    global _client, _unavailable_reason
    if _client is not None:
        return _client[MONGO_DB]
    if _unavailable_reason is not None:
        return None
    try:
        from pymongo import ASCENDING, MongoClient

        client = MongoClient(MONGO_URI, serverSelectionTimeoutMS=_CONNECT_TIMEOUT_MS)
        client.server_info()                     # forces a real connection attempt
        db = client[MONGO_DB]
        # Created on first use; there is no setup script to forget.
        db.messages.create_index([("conversation_id", ASCENDING), ("seq", ASCENDING)])
        db.conversations.create_index([("updated_at", -1)])
        _client = client
        return db
    except Exception as e:
        _unavailable_reason = f"{type(e).__name__}: {e}"
        return None


def is_available() -> tuple[bool, str]:
    return (True, "connected") if _db() is not None else (False, _unavailable_reason or "unavailable")


# --------------------------------------------------------------------------
# conversations
# --------------------------------------------------------------------------

def _title_from(text: str, limit: int = 48) -> str:
    """The first message, trimmed, is the title.

    Deliberately not an LLM call: titling is a convenience, and spending 20
    seconds of local-model time on it would make starting a conversation feel
    broken.
    """
    clean = " ".join(str(text).split())
    if not clean:
        return "New chat"
    return clean if len(clean) <= limit else clean[: limit - 1].rstrip() + "…"


def create_conversation(first_message: str | None = None) -> str | None:
    db = _db()
    if db is None:
        return None
    now = datetime.now(timezone.utc)
    doc = {"title": _title_from(first_message) if first_message else "New chat",
           "created_at": now, "updated_at": now, "n_messages": 0}
    return str(db.conversations.insert_one(doc).inserted_id)


def list_conversations(limit: int = 50) -> list:
    """Most recently used first -- the ordering a chat sidebar needs."""
    db = _db()
    if db is None:
        return []
    rows = db.conversations.find().sort("updated_at", -1).limit(limit)
    return [{"id": str(r["_id"]), "title": r.get("title", "Untitled"),
             "updated_at": r.get("updated_at"), "n_messages": r.get("n_messages", 0)}
            for r in rows]


def rename_conversation(conversation_id: str, title: str) -> bool:
    db = _db()
    if db is None:
        return False
    from bson import ObjectId

    db.conversations.update_one({"_id": ObjectId(conversation_id)},
                                {"$set": {"title": _title_from(title)}})
    return True


def delete_conversation(conversation_id: str) -> bool:
    """Removes the conversation and its messages together, so a deleted
    conversation cannot leave orphaned messages behind."""
    db = _db()
    if db is None:
        return False
    from bson import ObjectId

    db.messages.delete_many({"conversation_id": conversation_id})
    db.conversations.delete_one({"_id": ObjectId(conversation_id)})
    return True


# --------------------------------------------------------------------------
# messages
# --------------------------------------------------------------------------

def add_message(conversation_id: str, role: str, content: str,
                trace: list | None = None, retrieved_context: list | None = None,
                domain: str | None = None, image_name: str | None = None) -> bool:
    """Append one turn. Charts are not stored -- see the module docstring."""
    db = _db()
    if db is None or not conversation_id:
        return False
    from bson import ObjectId

    seq = db.messages.count_documents({"conversation_id": conversation_id})
    db.messages.insert_one({
        "conversation_id": conversation_id, "role": role, "content": str(content),
        # traces and retrieved context are mixed types (strings, dicts); str()
        # them so a Mongo encoding error can never lose a whole turn
        "trace": [str(t) for t in (trace or [])],
        "retrieved_context": [str(c) for c in (retrieved_context or [])],
        "domain": domain, "image_name": image_name,
        "seq": seq, "created_at": datetime.now(timezone.utc),
    })

    update = {"$set": {"updated_at": datetime.now(timezone.utc)}, "$inc": {"n_messages": 1}}
    conv = db.conversations.find_one({"_id": ObjectId(conversation_id)})
    # Title the conversation from its first USER message, not from whichever
    # message happened to be first.
    if conv is not None and role == "user" and conv.get("n_messages", 0) == 0:
        update["$set"]["title"] = _title_from(content)
    db.conversations.update_one({"_id": ObjectId(conversation_id)}, update)
    return True


def load_messages(conversation_id: str) -> list:
    """Messages in order, shaped like st.session_state.messages."""
    db = _db()
    if db is None or not conversation_id:
        return []
    rows = db.messages.find({"conversation_id": conversation_id}).sort("seq", 1)
    return [{"role": r.get("role", "user"), "content": r.get("content", ""),
             "trace": r.get("trace", []), "retrieved_context": r.get("retrieved_context", []),
             "domain": r.get("domain"), "image_name": r.get("image_name"),
             "chart": None, "charts": None}          # not persisted, by design
            for r in rows]


def stats() -> dict:
    db = _db()
    if db is None:
        return {"available": False, "reason": _unavailable_reason}
    return {"available": True, "database": MONGO_DB,
            "conversations": db.conversations.count_documents({}),
            "messages": db.messages.count_documents({})}


if __name__ == "__main__":
    import json

    ok, reason = is_available()
    print(f"MongoDB at {MONGO_URI}: {reason}")
    if not ok:
        raise SystemExit(1)

    cid = create_conversation()
    add_message(cid, "user", "anything unusual in KIC 5358624")
    add_message(cid, "assistant", "KIC 5358624 hosts Kepler-428 b...",
                trace=["[selector] task=detect_anomaly"], domain="astronomy")
    print(f"\ncreated {cid}, {len(load_messages(cid))} message(s)")
    print("conversations:", json.dumps(list_conversations(3), indent=2, default=str))
    delete_conversation(cid)
    print("\ncleaned up; stats:", stats())
